const storedLocale = (() => {
  try { return localStorage.getItem('pw-language'); } catch (error) { return null; }
})();
const browserLocale = globalThis.navigator?.languages?.[0] || globalThis.navigator?.language || 'fr';
let currentLanguage = storedLocale === 'en' || storedLocale === 'fr'
  ? storedLocale
  : (/^en(?:-|$)/i.test(browserLocale) ? 'en' : 'fr');

export const language = () => currentLanguage;
export const locale = () => currentLanguage === 'en' ? 'en-US' : 'fr-FR';

export function t(key, values = {}) {
  const template = messages[currentLanguage][key] || messages.fr[key] || key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ''));
}

export function translate(text) {
  if (currentLanguage === 'en' && englishText[text]) return englishText[text];
  for (const [key, french] of Object.entries(messages.fr)) {
    if (text === french) return messages[currentLanguage][key] || french;
  }
  return text;
}

export function setLanguage(value) {
  if (!Object.hasOwn(messages, value)) return;
  currentLanguage = value;
  try { localStorage.setItem('pw-language', value); } catch (error) { /* language selection remains active for this page */ }
}

export function formatDate(value, options = { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric' }) {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? String(value ?? '') : new Intl.DateTimeFormat(locale(), options).format(date);
}

export function formatDateTime(value, options = { dateStyle: 'medium', timeStyle: 'short' }) {
  const normalized = typeof value === 'string' ? value.replace(' ', 'T') : value;
  return formatDate(normalized, options);
}

export function applyStaticTranslations() {
  document.documentElement.lang = currentLanguage;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-attr]')) {
    for (const [attribute, key] of Object.entries(JSON.parse(node.dataset.i18nAttr))) node.setAttribute(attribute, t(key));
  }
}
